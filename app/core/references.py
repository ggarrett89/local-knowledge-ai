"""Human-readable source references, built only from real provenance metadata.

Nothing here is generated by an LLM and unknown fields are never invented: a field that
is absent from the provenance is simply left out of the reference.
"""

from __future__ import annotations

from app.core.models import Provenance


def format_pages(p: Provenance) -> str:
    if p.page_start is None:
        return ""
    if p.page_end is None or p.page_end == p.page_start:
        return f"p. {p.page_start}"
    return f"pp. {p.page_start}-{p.page_end}"


def format_reference(p: Provenance) -> str:
    """Examples: ``Book Title, p. 95``; ``Book Title, pp. 95-96``; ``Docs, § Install, https://...``."""
    parts = [p.title]
    pages = format_pages(p)
    if pages:
        parts.append(pages)
    if p.section:
        parts.append(f"\u00a7 {p.section}")
    if p.url:
        parts.append(p.url)
    if p.path:
        location = f"{p.repo}:{p.path}" if p.repo else p.path
        if p.line_start is not None:
            end = p.line_end if p.line_end is not None and p.line_end != p.line_start else None
            location += f":{p.line_start}" + (f"-{end}" if end is not None else "")
        parts.append(location)
    return ", ".join(parts)
