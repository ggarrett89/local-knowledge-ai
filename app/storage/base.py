"""Storage interfaces. Services depend on these, not on SQLite or ChromaDB directly."""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Protocol, Sequence

from app.core.models import Chunk, DocumentRecord, SearchHit


class MetadataStore(Protocol):
    def ensure_category(self, slug: str, description: Optional[str] = None) -> bool: ...
    def list_categories(self) -> List[Dict[str, Optional[str]]]: ...
    def upsert_document(self, doc: DocumentRecord) -> None: ...
    def get_document(self, document_id: str) -> Optional[DocumentRecord]: ...
    def find_by_hash(self, file_hash: str) -> Optional[DocumentRecord]: ...
    def find_by_path(self, file_path: str) -> List[DocumentRecord]: ...
    def list_documents(
        self,
        *,
        category: Optional[str] = None,
        topics: Optional[Sequence[str]] = None,
        source_type: Optional[str] = None,
        status: Optional[str] = None,
    ) -> List[DocumentRecord]: ...
    def remove_document(self, document_id: str) -> bool: ...
    def record_error(
        self,
        stage: str,
        message: str,
        *,
        document_id: Optional[str] = None,
        source_uri: Optional[str] = None,
    ) -> None: ...
    def list_errors(self, document_id: Optional[str] = None) -> List[Dict[str, Any]]: ...
    def clear_errors(self, document_id: str) -> None: ...
    def stats(self) -> Dict[str, Any]: ...
    def close(self) -> None: ...


class VectorStore(Protocol):
    def upsert(self, chunks: Sequence[Chunk], vectors: Sequence[Sequence[float]]) -> None: ...
    def query(
        self, vector: Sequence[float], k: int, document_ids: Optional[Sequence[str]] = None
    ) -> List[SearchHit]: ...
    def delete_document(self, document_id: str) -> int: ...
    def prune_document(self, document_id: str, keep_count: int) -> int: ...
    def count(self) -> int: ...
    def count_document(self, document_id: str) -> int: ...
    def close(self) -> None: ...
